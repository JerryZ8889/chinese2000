// Fisher-Yates 洗牌算法
function shuffleArray(array) {
  const shuffled = [...array];
  for (let i = shuffled.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [shuffled[i], shuffled[j]] = [shuffled[j], shuffled[i]];
  }
  return shuffled;
}

// 将字数组按单元划分
function splitIntoUnits(chars, unitSize = 20) {
  const units = [];
  for (let i = 0; i < chars.length; i += unitSize) {
    units.push({
      unit: Math.floor(i / unitSize) + 1,
      chars: chars.slice(i, i + unitSize)
    });
  }
  return units;
}

// 生成阶段数据
function generateStageData(stageNum, chars) {
  // 打乱字序
  const shuffledChars = shuffleArray(chars);
  
  // 按单元划分
  const units = splitIntoUnits(shuffledChars);
  
  return {
    stage: stageNum,
    totalChars: chars.length,
    totalUnits: units.length,
    units: units
  };
}

// 主函数
function main() {
  const outputDir = path.join(__dirname, '..', 'src', 'data');
  
  // 确保输出目录存在
  if (!fs.existsSync(outputDir)) {
    fs.mkdirSync(outputDir, { recursive: true });
  }
  
  // 生成每个阶段的数据
  Object.entries(stageChars).forEach(([key, chars]) => {
    const stageNum = parseInt(key.replace('stage', ''));
    const data = generateStageData(stageNum, chars);
    
    const outputPath = path.join(outputDir, `stage${stageNum}.json`);
    fs.writeFileSync(outputPath, JSON.stringify(data, null, 2), 'utf-8');
    
    console.log(`阶段 ${stageNum}: ${data.totalChars} 字, ${data.totalUnits} 单元 -> ${outputPath}`);
  });
  
  console.log('\n字表数据生成完成！');
  console.log('注意：请补充完整的字表数据（目前只有部分示例字）');
}

main();
